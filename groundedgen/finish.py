"""Final steps after the Kaggle test run, and a plain-language results summary.

``python -m groundedgen.finish ghd_outputs.zip configs/local.yaml``

1. merges the downloaded Kaggle outputs,
2. drops stale records and rebuilds every table and figure on test
   (``analysis.build_all``),
3. writes the human-evaluation sheet and rating pages and the judge-check
   pages (unless they exist already, so returned answers are never lost),
4. writes ``outputs/analysis/results_summary.md``.

Run ``python -m groundedgen.finish --rebuild configs/local.yaml`` after the
ratings and judge labels are back to refresh T6, T8 and the summary.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Mapping, Sequence

import pandas as pd

from groundedgen import utils
from groundedgen import taxonomy as tx


def _ci(d: Mapping[str, float] | None, digits: int = 2) -> str:
    if not isinstance(d, Mapping) or d.get("estimate") is None:
        return "n/a"
    if d.get("low") is None or d.get("high") is None:
        return f"{d['estimate']:.{digits}f}"
    return f"{d['estimate']:.{digits}f} [{d['low']:.{digits}f}, {d['high']:.{digits}f}]"


def _short(name: str | None) -> str:
    return "" if not name else name.split("/")[-1]


def primary_keys(cfg: Mapping[str, Any], extractor: str) -> dict[str, str]:
    """``numbers.json`` rate-key prefix of each condition's primary configuration."""
    vlm = _short(cfg["generation"]["vlms"]["primary"])
    llm = _short(cfg["generation"]["llms"]["primary"])
    ext = _short(extractor)
    return {"A": f"A|{vlm}|", "A-F": f"A-F|{vlm}|", "B": f"B|{llm}|{ext}",
            "B-Abs": f"B-Abs|{llm}|{ext}", "APG": f"APG|{llm}|{ext}", "C": f"C|{llm}|",
            "C-Mask": f"C-Mask|{llm}|"}


def ucr_by_condition(cfg: Mapping[str, Any], split: str) -> dict[str, Any]:
    """UCR per condition × generator × extractor from the judge records."""
    from groundedgen import judge

    records = judge.judged_descriptions(cfg, split)
    if records.empty:
        return {}
    out = {}
    for (c, g, e), group in records.groupby(["condition", "generator", "extractor"], dropna=False):
        key = f"{c}|{_short(g)}|{_short(e) if isinstance(e, str) else ''}"
        out[key] = judge.ucr(group.to_dict("records"))
    return out


def summary_markdown(cfg: Mapping[str, Any], numbers: Mapping[str, Any],
                     extraction: Mapping[str, Any] | None, tests: pd.DataFrame | None) -> str:
    """Every headline number in sentences, with 95% CIs, plus deviations."""
    extractor = numbers["primary_extractor"]
    keys = primary_keys(cfg, extractor)
    rates = numbers["rates"]
    L = [f"# Results summary ({numbers['split']})", "",
         "Generated by `groundedgen.finish` from `numbers.json`; every value is a point "
         "estimate with a 95% item-cluster bootstrap CI. Primary configuration: "
         f"VLM {_short(cfg['generation']['vlms']['primary'])}, LLM "
         f"{_short(cfg['generation']['llms']['primary'])}, extractor {_short(extractor)}.", ""]

    ann = numbers.get("annotation", {})
    split = numbers["split"]
    if ann:
        ag = ann["agreement"].get(split) or {}
        L += ["## Data and annotation (T1)", ""]
        L.append("Cohen's kappa between the two annotators: " + ", ".join(
            f"{a} {ag[a]['kappa']:.2f} (raw {ag[a]['raw_agreement']:.2f})" for a in tx.ATTRIBUTES if a in ag)
            + f". Material gold is `unknown` for {ann['counts'][split]['material_unknown_share']:.1%} "
            "of items. All disagreements were adjudicated by a third team member.")
        L.append("")

    if extraction:
        L += ["## Extraction (T2, F2)", ""]
        for model, by_attr in extraction["results"].items():
            parts = []
            for a in tx.ATTRIBUTES:
                m = by_attr[a]
                fa = m["forced_accuracy"]
                parts.append(f"{a} {fa['estimate']:.2f} (coverage at threshold {m['coverage']:.0%})")
            L.append(f"- {_short(model)}: forced accuracy " + "; ".join(parts) + ".")
        L.append("")

    L += ["## Main results, primary configuration (T3)", "",
          "| Condition | " + " | ".join(f"{a} HR" for a in tx.ATTRIBUTES) + " |",
          "|---|" + "---|" * len(tx.ATTRIBUTES)]
    for cond, prefix in keys.items():
        cells = [_ci(rates.get(f"{prefix}|{a}", {}).get("HR")) for a in tx.ATTRIBUTES]
        L.append(f"| {cond} | " + " | ".join(cells) + " |")
    L.append("")

    L += ["## RQ1: where do B's hallucinations come from? (T4)", ""]
    for a in tx.ATTRIBUTES:
        r = rates.get(f"{keys['B']}|{a}", {})
        L.append(f"- {a}: EP {_ci(r.get('EP'))}, GD {_ci(r.get('GD'))}, GF {_ci(r.get('GF'))}; "
                 f"extraction share {_ci(r.get('extraction_share'))}.")
    diff = numbers.get("rq1_gd_diff_B_minus_C", {})
    if diff:
        L.append("- GD(B) − GD(C) per LLM and attribute: " + "; ".join(
            f"{k} {_ci(v, 3)}" for k, v in diff.items()) + ".")
    L.append("")

    L += ["## RQ2: does abstention survive the LLM? (T5)", ""]
    for cond in ("B-Abs", "APG", "C-Mask"):
        parts = [f"{a} leakage {_ci(rates.get(f'{keys[cond]}|{a}', {}).get('leakage'))}, "
                 f"inflation {_ci(rates.get(f'{keys[cond]}|{a}', {}).get('inflation'))}" for a in tx.ATTRIBUTES]
        L.append(f"- {cond}: " + "; ".join(parts) + ".")
    L.append("")

    if tests is not None and len(tests):
        L += ["## Planned paired tests (exact McNemar, Holm)", ""]
        for _, t in tests.iterrows():
            verdict = "significant" if t["reject"] else "not significant"
            L.append(f"- {_short(t['llm'])} {t['attribute']}: {t['left']} vs {t['right']}, "
                     f"HR difference {t['rate_diff']:+.3f}, Holm p = {t['p_holm']:.3g} ({verdict}; "
                     f"{int(t['n10'])} vs {int(t['n01'])} discordant items).")
        L.append("")

    ucr = numbers.get("ucr", {})
    if ucr:
        L += ["## Non-attribute claims (judge, UCR)", ""]
        for cond, prefix in keys.items():
            u = ucr.get(prefix)
            if u and u.get("n"):
                L.append(f"- {cond}: UCR {u['ucr']:.2f} unsupported claims per description, "
                         f"{u['subjective_per_description']:.2f} subjective; parse errors "
                         f"{u['parse_error_rate']:.1%} (n = {u['n']}).")
        L.append("")

    val = numbers.get("validation", {})
    L += ["## Measurement validation (T8)", ""]
    if "claims" in val:
        c = val["claims"]
        L.append("- Claim extractor vs. labels both labellers agree on (60 dev descriptions): " + "; ".join(
            f"{a} P {c[a]['vs_agreed']['precision']:.2f} / R {c[a]['vs_agreed']['recall']:.2f}"
            for a in tx.ATTRIBUTES) + ".")
    if "judge" in val:
        j = val["judge"]
        L.append(f"- Judge vs. labeller a: P {j['vs_a']['precision']:.2f} / R {j['vs_a']['recall']:.2f}; "
                 f"vs. b: P {j['vs_b']['precision']:.2f} / R {j['vs_b']['recall']:.2f}; human kappa "
                 f"{j['human_kappa_any_claim']:.2f} (n = {j['n_descriptions']}).")
    else:
        L.append("- Judge validation: pending (labels not returned yet).")
    for k, v in val.get("apg_fallback", {}).items():
        L.append(f"- APG fallback rate {k}: {v['rate']:.1%} (n = {v['n']}).")
    L.append("")

    he = numbers.get("human_eval")
    L += ["## Human evaluation (T6)", ""]
    if he:
        for cond, m in he["conditions"].items():
            L.append(f"- {cond}: fluency {_ci(m['fluency'])}, faithfulness {_ci(m['faithfulness'])}, "
                     f"usefulness {_ci(m['usefulness'])}, publish-as-is {_ci(m['publish'])}.")
        L.append("- Krippendorff's alpha: " + ", ".join(f"{k} {v:.2f}" for k, v in he["alpha"].items()) + ".")
        for t in he["tests"]:
            L.append(f"- {t['scale']}: {t['left']} − {t['right']} mean difference {t['mean_diff']:+.2f}, "
                     f"Holm p = {t['p_holm']:.3g}.")
    else:
        L.append("- Pending (ratings not returned yet).")
    L.append("")

    L += ["## Deviations from the build specification", "",
          "- Material annotation agreement is below the 0.6 target (see T1); guidelines were "
          "refined once on dev (v1.1) and frozen before test; test was not re-labelled.",
          "- Claim extractor: one rule added on dev (colors of logos, prints, embroidery, trim "
          "are not garment colors) and re-validated; category recall is limited by the spec's "
          "first-mention rule.",
          f"- Judge run on the primary configuration only; judge validation on "
          f"{cfg['judge'].get('validation_max_n', 'n/a')} test descriptions (10 per condition) "
          "instead of 20% of all test descriptions.",
          f"- Human evaluation on {cfg['human_eval']['n_items']} items (spec: 50), keeping "
          f"{cfg['human_eval']['min_ethnic']} ethnic-wear items.",
          "- The judge is the same model family as one generator (Qwen2.5).", ""]
    return "\n".join(L)


def write_summary(cfg: Mapping[str, Any], split: str = "test") -> Path:
    project_dir = Path(cfg["project_dir"])
    out_dir = project_dir / "outputs" / "analysis"
    suffix = "" if split == "test" else f"_{split}"
    numbers = json.loads((out_dir / f"numbers{suffix}.json").read_text(encoding="utf-8"))
    ev_path = project_dir / "outputs" / "extraction" / "evaluation.json"
    extraction = json.loads(ev_path.read_text(encoding="utf-8")) if ev_path.exists() and split == "test" else None
    tests_path = out_dir / f"tests_mcnemar{suffix}.csv"
    tests = pd.read_csv(tests_path) if tests_path.exists() else None
    path = out_dir / f"results_summary{suffix}.md"
    path.write_text(summary_markdown(cfg, numbers, extraction, tests), encoding="utf-8")
    return path


def rebuild(cfg: Mapping[str, Any], split: str = "test") -> dict[str, Any]:
    """Tables, figures, UCR and the summary from what is on disk."""
    from groundedgen import analysis, generate

    for s in ("dev", "test"):
        generate.purge_stale(cfg, s)
    result = analysis.build_all(cfg, split)
    out_dir = Path(cfg["project_dir"]) / "outputs" / "analysis"
    suffix = "" if split == "test" else f"_{split}"
    numbers_path = out_dir / f"numbers{suffix}.json"
    numbers = json.loads(numbers_path.read_text(encoding="utf-8"))
    numbers["ucr"] = analysis._plain(ucr_by_condition(cfg, split))
    utils.write_json(numbers_path, numbers)
    result["summary"] = str(write_summary(cfg, split))
    return result


def finish(cfg: Mapping[str, Any], zip_path: str | Path | None) -> dict[str, Any]:
    from groundedgen import human_eval, judge, kaggle

    out: dict[str, Any] = {}
    if zip_path:
        out["merged"] = kaggle.merge_zip(zip_path, cfg["project_dir"])
    out.update(rebuild(cfg, "test"))
    he_dir = human_eval.out_dir(cfg)
    if not (he_dir / "key.csv").exists():
        out["human_eval"] = human_eval.prepare(cfg)
    jdir = utils.project_path(cfg, "outputs", "validation", "judge")
    if not (jdir / "judge_validation_key.csv").exists():
        out["judge_validation"] = judge.prepare_validation(cfg, "test")
    out["pages"] = sorted(str(p) for p in [*he_dir.glob("rate_*.html"), *jdir.glob("*.html")])
    return out


def main(argv: Sequence[str] | None = None) -> None:
    """``python -m groundedgen.finish [ghd_outputs.zip | --rebuild] [extra.yaml ...]``."""
    import argparse
    import logging

    parser = argparse.ArgumentParser(description=main.__doc__)
    parser.add_argument("zip", nargs="?", help="Kaggle ghd_outputs.zip (omit with --rebuild)")
    parser.add_argument("configs", nargs="*")
    parser.add_argument("--rebuild", action="store_true", help="only rebuild results and summary")
    args = parser.parse_args(argv)
    configs = list(args.configs)
    zip_path = args.zip
    if zip_path and zip_path.endswith((".yaml", ".yml")):
        configs.insert(0, zip_path)
        zip_path = None
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    cfg = utils.load_config(extra_paths=configs)
    result = rebuild(cfg, "test") if args.rebuild else finish(cfg, zip_path)
    print(json.dumps(result, indent=2, default=str))


if __name__ == "__main__":
    main()
